def _start_marker():
    try:
        with open(f"/proc/{os.getpid()}/stat", encoding="utf-8") as stream:
            stat = stream.read()
        fields = stat[stat.rfind(")") + 2:].split()
        return fields[19] if len(fields) > 19 else None
    except OSError:
        return None


def _active_group_members():
    """Return non-zombie members of this launcher's process group."""
    own_pid = os.getpid()
    group_id = os.getpgrp()
    members = []
    try:
        proc_entries = os.scandir("/proc")
    except OSError:
        # The ps helper shares this process group; track its pid so it is not
        # reported as a leaked group member.
        ps_proc = subprocess.Popen(
            ["ps", "-eo", "pid=,pgid=,stat="],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        ps_out, ps_err = ps_proc.communicate()
        if ps_proc.returncode != 0:
            raise RuntimeError(
                "cannot enumerate process group: " + ps_err.strip()
            )
        for line in ps_out.splitlines():
            fields = line.split()
            if len(fields) < 3:
                continue
            try:
                pid = int(fields[0])
                process_group = int(fields[1])
            except ValueError:
                continue
            state = fields[2]
            if pid not in (own_pid, ps_proc.pid) and process_group == group_id and not state.startswith("Z"):
                members.append(pid)
        return members
    with proc_entries:
        for entry in proc_entries:
            if not entry.name.isdigit():
                continue
            pid = int(entry.name)
            if pid == own_pid:
                continue
            try:
                with open(f"/proc/{pid}/stat", encoding="utf-8") as stream:
                    stat = stream.read()
                fields = stat[stat.rfind(")") + 2:].split()
                state = fields[0]
                process_group = int(fields[2])
            except (OSError, ValueError, IndexError):
                continue
            if process_group == group_id and state != "Z":
                members.append(pid)
    return members


def _stop_remaining_group_members(timeout=1.0):
    """Prevent a successful direct script from leaking background workers."""
    members = _active_group_members()
    for pid in members:
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
    deadline = time.monotonic() + timeout
    while members and time.monotonic() < deadline:
        time.sleep(0.05)
        members = _active_group_members()
    for pid in members:
        try:
            os.kill(pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    kill_deadline = time.monotonic() + max(1.0, timeout)
    while members and time.monotonic() < kill_deadline:
        time.sleep(0.05)
        members = _active_group_members()
    if members:
        raise RuntimeError(f"process group still has live members: {members}")


