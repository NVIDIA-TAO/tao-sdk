def _parse_spec_path(path: str) -> list[str | int]:
    """Parse a dotted path with optional list indexes into traversal tokens."""
    if not isinstance(path, str) or not path:
        raise ValueError("Declared spec paths must be non-empty strings")

    tokens: list[str | int] = []
    pos = 0
    expect_key = True
    while pos < len(path):
        if path[pos] == ".":
            if expect_key:
                raise ValueError(f"Invalid declared spec path: {path!r}")
            expect_key = True
            pos += 1
            continue
        if path[pos] == "[":
            end = path.find("]", pos + 1)
            if end < 0 or not path[pos + 1:end].isdigit() or expect_key:
                raise ValueError(f"Invalid declared spec path: {path!r}")
            tokens.append(int(path[pos + 1:end]))
            pos = end + 1
            expect_key = False
            continue
        end = pos
        while end < len(path) and path[end] not in ".[":
            if path[end] == "]":
                raise ValueError(f"Invalid declared spec path: {path!r}")
            end += 1
        key = path[pos:end]
        if not key or not expect_key:
            raise ValueError(f"Invalid declared spec path: {path!r}")
        tokens.append(key)
        expect_key = False
        pos = end
    if expect_key:
        raise ValueError(f"Invalid declared spec path: {path!r}")
    return tokens


def _get_nested(value: Any, path: str) -> Any:
    current = value
    try:
        for token in _parse_spec_path(path):
            current = current[token]
    except (KeyError, IndexError, TypeError):
        return _MISSING
    return current


def _set_nested(value: dict, path: str, replacement: str) -> None:
    tokens = _parse_spec_path(path)
    current: Any = value
    for index, token in enumerate(tokens[:-1]):
        next_token = tokens[index + 1]
        if isinstance(token, int):
            if not isinstance(current, list) or token >= len(current):
                raise ValueError(
                    f"Output path {path!r} references a missing list element"
                )
            current = current[token]
            continue
        if not isinstance(current, dict):
            raise ValueError(f"Output path {path!r} crosses a non-mapping value")
        if token not in current:
            if isinstance(next_token, int):
                raise ValueError(
                    f"Output path {path!r} references a missing list value"
                )
            current[token] = {}
        current = current[token]

    leaf = tokens[-1]
    if isinstance(leaf, int):
        if not isinstance(current, list) or leaf >= len(current):
            raise ValueError(f"Output path {path!r} references a missing list element")
        current[leaf] = replacement
    else:
        if not isinstance(current, dict):
            raise ValueError(f"Output path {path!r} crosses a non-mapping value")
        current[leaf] = replacement


def _is_remote_uri(value: str) -> bool:
    parsed = urlsplit(value)
    if parsed.scheme.lower() == "file":
        return False
    return bool(parsed.scheme and (parsed.netloc or "://" in value))


def _find_remote_uri(value: Any) -> str | None:
    if isinstance(value, str):
        return value if _is_remote_uri(value) else None
    if isinstance(value, Mapping):
        for nested in value.values():
            found = _find_remote_uri(nested)
            if found:
                return found
    elif isinstance(value, Sequence) and not isinstance(value, (str, bytes, bytearray)):
        for nested in value:
            found = _find_remote_uri(nested)
            if found:
                return found
    return None


def _process_start_marker(pid: int) -> str | None:
    """Return Linux process start ticks, which disambiguate PID reuse."""
    try:
        stat = Path(f"/proc/{pid}/stat").read_text(encoding="utf-8")
    except OSError:
        return None
    closing_paren = stat.rfind(")")
    if closing_paren < 0:
        return None
    fields_after_name = stat[closing_paren + 2:].split()
    # The first value is field 3 (state); starttime is field 22.
    return fields_after_name[19] if len(fields_after_name) > 19 else None


def _read_tail(
    path: Path,
    line_count: int,
    max_bytes: int = _LOG_TAIL_MAX_BYTES,
) -> str:
    """Read at most ``line_count`` lines without scanning the whole log."""
    if line_count <= 0:
        return ""
    block_size = 64 * 1024
    with path.open("rb") as stream:
        stream.seek(0, os.SEEK_END)
        remaining = stream.tell()
        chunks: list[bytes] = []
        newline_count = 0
        bytes_read = 0
        while (
            remaining > 0
            and newline_count <= line_count
            and bytes_read < max_bytes
        ):
            size = min(block_size, remaining, max_bytes - bytes_read)
            remaining -= size
            stream.seek(remaining)
            chunk = stream.read(size)
            chunks.append(chunk)
            newline_count += chunk.count(b"\n")
            bytes_read += len(chunk)
    data = b"".join(reversed(chunks))
    return b"".join(data.splitlines(keepends=True)[-line_count:]).decode(
        "utf-8", errors="replace"
    )


class VirtualEnvSDK:
    """Run asynchronous Python jobs in one existing local virtual environment.

    Args:
        venv_path: A virtual-environment root containing ``pyvenv.cfg`` and an
            executable ``bin/python``.
        work_dir: Root for isolated ``jobs/<job-id>`` directories. When
            omitted, uses ``TAO_SDK_STATE_DIR/virtualenv`` (or
            ``~/.tao_sdk/virtualenv``), so recovery does not depend on cwd.
        state_file: SQLite state path. A ``.json`` suffix is converted to
            ``.db`` for compatibility with the other SDK constructors.

    ``gpu_count`` is launch metadata, not a device reservation. A positive
    count without ``gpu_ids`` preserves the caller's existing CUDA visibility.
    Set ``gpu_count=0`` to hide CUDA devices, or pass ``gpu_ids`` to set
    ``CUDA_VISIBLE_DEVICES`` explicitly.
    """

    def __init__(
        self,
        venv_path: str | os.PathLike[str],
        work_dir: str | os.PathLike[str] | None = None,
        state_file: str | os.PathLike[str] | None = None,
    ):
        self.venv_path = self._validate_venv(venv_path)
        self.python_path = self.venv_path / "bin" / "python"
        using_default_layout = work_dir is None and state_file is None
        if work_dir is None:
            default_state_file, _default_db = resolve_sdk_state_paths()
            resolved_work_dir = Path(default_state_file).parent / "virtualenv"
        else:
            resolved_work_dir = Path(work_dir).expanduser()
        self.work_dir = resolved_work_dir.resolve()
        self.jobs_dir = self.work_dir / "jobs"
        self.jobs_dir.mkdir(parents=True, exist_ok=True)

        raw_state_path = Path(state_file).expanduser() if state_file else self.work_dir / "tao_session.db"
        if raw_state_path.suffix == ".json":
            raw_state_path = raw_state_path.with_suffix(".db")
        if not raw_state_path.is_absolute():
            raw_state_path = Path.cwd() / raw_state_path
        raw_state_path.parent.mkdir(parents=True, exist_ok=True)

        if using_default_layout:
            legacy_db = Path.cwd() / ".tao" / "virtualenv" / "tao_session.db"
            if (
                legacy_db.is_file()
                and legacy_db.resolve() != raw_state_path.resolve()
            ):
                imported = merge_legacy_database(
                    legacy_db,
                    raw_state_path.resolve(),
                )
                if imported:
                    logger.info(
                        "Migrated %d VirtualEnv jobs from legacy state %s",
                        imported,
                        legacy_db,
                    )

        self._store = JobStore(db_path=str(raw_state_path.resolve()))
        self._jobs: dict[str, Job] = {}
        self._processes: dict[str, subprocess.Popen] = {}
        self._hooks: dict[str, dict] = {}
        self._canceled: set[str] = set()
        self._lock = threading.RLock()

    @staticmethod
    def _validate_venv(venv_path: str | os.PathLike[str]) -> Path:
        path = Path(venv_path).expanduser().resolve()
        if not path.is_dir():
            raise ValueError(f"Virtual environment does not exist: {path}")
        if not (path / "pyvenv.cfg").is_file():
            raise ValueError(
                f"Not a Python virtual environment (pyvenv.cfg is missing): {path}"
            )
        python_path = path / "bin" / "python"
        if not python_path.is_file() or not os.access(python_path, os.X_OK):
            raise ValueError(f"Virtual environment Python is not executable: {python_path}")
        return path

    # ------------------------------------------------------------------
    # Job submission
    # ------------------------------------------------------------------

    def create_python_job(
        self,
        script: str | os.PathLike[str],
        specs: dict | None = None,
        config_format: str = "json",
        script_args: Sequence[str] | None = None,
        env_vars: dict[str, str] | None = None,
        inputs: dict | None = None,
        outputs: dict | list | None = None,
        upload_excludes: Sequence[str] | None = None,
        cwd: str | os.PathLike[str] | None = None,
        network_arch: str = "",
        action: str = "train",
        hooks: dict | None = None,
        gpu_count: int = 1,
        gpu_ids: Sequence[int] | str | None = None,
    ) -> Job:
        """Launch ``script`` directly with the virtual-environment interpreter.

        ``script_args`` is an argv sequence, not a command string. Tokens may
        contain ``{config_path}``, ``{results_dir}``, or ``{job_id}``.
        Declared output spec keys are rewritten to job-local paths before the
        nested spec is serialized. Remote declared inputs are rejected because
        this backend intentionally performs no implicit downloads.
        """
        launch_cwd = self._validate_cwd(cwd)
        script_path = Path(script).expanduser()
        if not script_path.is_absolute():
            script_path = launch_cwd / script_path
        script_path = script_path.resolve()
        if not script_path.is_file():
            raise ValueError(f"Python script does not exist: {script_path}")

        normalized_args = self._validate_script_args(script_args)
        normalized_gpu_ids = self._validate_gpu_request(gpu_count, gpu_ids)
        normalized_env = self._validate_env_vars(env_vars)
        normalized_hooks = self._validate_hooks(hooks)
        excludes = self._validate_string_sequence(upload_excludes, "upload_excludes")
        normalized_format = self._validate_config_format(config_format)
        # Output placeholders may be null until _route_outputs replaces them.
        # _write_spec performs the final format-specific validation afterward.
        spec_copy = normalize_specs(specs)

        self._validate_local_inputs(spec_copy, inputs)

        job_id = str(uuid.uuid4())
        job_dir = self.jobs_dir / job_id
        spec_dir = job_dir / "spec"
        results_dir = job_dir / "results"
        logs_dir = job_dir / "logs"
        config_path = spec_dir / f"spec.{normalized_format}"

        placeholders = {
            "config_path": str(config_path),
            "results_dir": str(results_dir),
            "job_id": job_id,
        }
        rendered_args = [self._render_arg(token, placeholders) for token in normalized_args]
        script_argv = [str(self.python_path), str(script_path), *rendered_args]
        wrapper_path = job_dir / "launch_job.py"
        exit_record_path = job_dir / "exit_status.json"
        launcher_record_path = job_dir / "launcher_status.json"
        start_gate_path = job_dir / "start_authorized"
        cancel_path = job_dir / "cancel_requested"
        job_dir_created = False
        try:
            job_dir.mkdir(parents=True, exist_ok=False)
            job_dir_created = True
            for path in (spec_dir, results_dir, logs_dir):
                path.mkdir()
            routed_outputs = self._route_outputs(spec_copy, outputs, results_dir)
            self._write_spec(config_path, spec_copy, normalized_format)
            wrapper_path.write_text(_JOB_WRAPPER_SOURCE, encoding="utf-8")
        except BaseException:
            if job_dir_created:
                shutil.rmtree(job_dir, ignore_errors=True)
            raise
        launcher_argv = [
            str(self.python_path),
            str(wrapper_path),
            str(exit_record_path),
            str(launcher_record_path),
            str(start_gate_path),
            str(cancel_path),
            *script_argv,
        ]

        process_env = os.environ.copy()
        process_env.pop("PYTHONHOME", None)
        process_env.update(normalized_env)
        process_env["VIRTUAL_ENV"] = str(self.venv_path)
        current_path = process_env.get("PATH", "")
        process_env["PATH"] = str(self.venv_path / "bin") + (
            os.pathsep + current_path if current_path else ""
        )
        process_env["TAO_JOB_ID"] = job_id
        process_env["TAO_RESULTS_ROOT"] = str(results_dir)
        if "PYTHONUNBUFFERED" not in normalized_env:
            process_env["PYTHONUNBUFFERED"] = "1"
        if normalized_gpu_ids is not None:
            process_env["CUDA_VISIBLE_DEVICES"] = ",".join(
                str(device_id) for device_id in normalized_gpu_ids
            )
        elif gpu_count == 0:
            process_env["CUDA_VISIBLE_DEVICES"] = ""

        log_path = logs_dir / "job.log"
        metadata = {
            "job_id": job_id,
            "status": "Pending",
            "pid": None,
            "process_start_marker": None,
            "return_code": None,
            "message": "Job launch is pending",
            "launch_started_at": time.time(),
            "argv": script_argv,
            "launcher_argv": launcher_argv,
            "launcher_path": str(wrapper_path),
            "launcher_record_path": str(launcher_record_path),
            "exit_record_path": str(exit_record_path),
            "start_gate_path": str(start_gate_path),
            "cancel_path": str(cancel_path),
            "cwd": str(launch_cwd),
            "venv_path": str(self.venv_path),
            "config_path": str(config_path),
            "results_dir": str(results_dir),
            "log_path": str(log_path),
            "outputs": routed_outputs,
            "upload_excludes": excludes,
            "gpu_count": gpu_count,
            "gpu_ids": normalized_gpu_ids,
        }
        job_record_created = False
        try:
            with self._lock:
                self._store.create_job(
                    job_id=job_id,
                    network_arch=network_arch,
                    action=action,
                    workspace_id="local",
                    backend_type="virtualenv",
                    backend_job_id="",
                    status="Pending",
                    image=str(self.python_path),
                    specs=spec_copy,
                    results_dir=str(results_dir),
                    local_results_dir=str(results_dir),
                )
                job_record_created = True
                self._write_metadata(job_dir, metadata)
        except BaseException:
            if job_record_created:
                try:
                    with self._lock:
                        self._store.compare_and_set_job_status(
                            job_id, ("Pending", "Running"), "Error"
                        )
                except Exception:
                    logger.exception("Failed to mark pending launch %s as Error", job_id)
            else:
                shutil.rmtree(job_dir, ignore_errors=True)
            raise

        process = None
        try:
            log_file = log_path.open("ab", buffering=0)
            try:
                process = subprocess.Popen(
                    launcher_argv,
                    cwd=str(launch_cwd),
                    env=process_env,
                    stdin=subprocess.DEVNULL,
                    stdout=log_file,
                    stderr=subprocess.STDOUT,
                    shell=False,
                    start_new_session=True,
                )
            finally:
                # Popen duplicated the descriptor for the child process.
                log_file.close()

            process_start_marker = _process_start_marker(process.pid)
            job = Job(
                id=job_id,
                network_arch=network_arch,
                action=action,
                workspace_id="local",
                backend_type="virtualenv",
                status="Running",
                backend_job_id=str(process.pid),
                results_dir=str(results_dir),
                local_results_dir=str(results_dir),
            )
            metadata.update({
                "status": "Running",
                "pid": process.pid,
                "process_start_marker": process_start_marker,
                "message": f"Process {process.pid} is running",
            })
            watcher = threading.Thread(
                target=self._watch_process,
                args=(job_id, process),
                name=f"tao-virtualenv-{job_id[:8]}",
                daemon=True,
            )
            with self._lock:
                if not self._store.update_job_backend_id(
                    job_id, str(process.pid), status="Running"
                ):
                    raise RuntimeError(
                        f"Pending job record disappeared during launch: {job_id}"
                    )
                self._write_metadata(job_dir, metadata)
                self._jobs[job_id] = job
                self._processes[job_id] = process
                self._hooks[job_id] = normalized_hooks
                watcher.start()
                self._authorize_launch(metadata)
        except BaseException as exc:
            metadata.update({
                "status": "Error",
                "message": f"Job launch failed: {type(exc).__name__}: {exc}",
            })
            try:
                self._write_metadata(job_dir, metadata)
            except Exception:
                logger.exception("Failed to write launch error metadata for %s", job_id)
            if process is not None:
                quiescent = self._abort_spawned_process(job_id, process)
                if not quiescent:
                    metadata.update({
                        "status": "Canceling",
                        "pid": process.pid,
                        "message": (
                            "Job launch failed after spawn and process-group "
                            "termination is not yet confirmed"
                        ),
                    })
                    try:
                        self._write_metadata(job_dir, metadata)
                    except Exception:
                        logger.exception(
                            "Failed to persist recoverable launch metadata for %s",
                            job_id,
                        )
            else:
                try:
                    with self._lock:
                        self._store.compare_and_set_job_status(
                            job_id, ("Pending", "Running"), "Error"
                        )
                except Exception:
                    logger.exception("Failed to persist launch error for %s", job_id)
                quiescent = True
            exc.tao_job_id = job_id
            exc.tao_launch_uncertain = not quiescent
            raise

        logger.info("Python job %s started as PID %s", job_id, process.pid)
        return job

    @staticmethod
    def _validate_cwd(cwd: str | os.PathLike[str] | None) -> Path:
        path = Path(cwd).expanduser().resolve() if cwd is not None else Path.cwd().resolve()
        if not path.is_dir():
            raise ValueError(f"Working directory does not exist: {path}")
        return path

    @staticmethod
    def _validate_script_args(script_args: Sequence[str] | None) -> list[str]:
        if script_args is None:
            return []
        if isinstance(script_args, (str, bytes, bytearray)):
            raise TypeError("script_args must be an argv sequence, not a command string")
        result = list(script_args)
        if not all(isinstance(token, str) for token in result):
            raise TypeError("Every script_args token must be a string")
        return result

    @staticmethod
    def _validate_string_sequence(value: Sequence[str] | None, name: str) -> list[str]:
        if value is None:
            return []
        if isinstance(value, (str, bytes, bytearray)):
            raise TypeError(f"{name} must be a sequence of strings")
        result = list(value)
        if not all(isinstance(item, str) for item in result):
            raise TypeError(f"{name} must contain only strings")
        return result

    @staticmethod
    def _validate_env_vars(env_vars: dict[str, str] | None) -> dict[str, str]:
        if env_vars is None:
            return {}
        if not isinstance(env_vars, dict):
            raise TypeError("env_vars must be a dictionary")
        if not all(isinstance(key, str) and isinstance(value, str)
                   for key, value in env_vars.items()):
            raise TypeError("env_vars keys and values must be strings")
        return dict(env_vars)

    @staticmethod
    def _validate_hooks(hooks: dict | None) -> dict:
        if hooks is None:
            return {}
        if not isinstance(hooks, dict):
            raise TypeError("hooks must be a dictionary of callback functions")
        supported = {"on_complete", "on_error"}
        unknown = set(hooks) - supported
        if unknown:
            raise ValueError(
                "Unsupported virtualenv hook(s): " + ", ".join(sorted(unknown))
            )
        if not all(callable(callback) for callback in hooks.values()):
            raise TypeError("Every hook value must be callable")
        return dict(hooks)

    def _abort_spawned_process(
        self, job_id: str, process: subprocess.Popen, timeout: float = 5.0,
    ) -> bool:
        """Roll back a spawned process, retaining identity until quiescent."""
        try:
            with self._lock:
                entry = self._store.get_job(job_id)
                metadata = self._read_metadata_from_entry(entry) if entry else {}
                self._request_cancel(metadata)
        except Exception:
            logger.exception(
                "Failed to persist pre-termination cancel intent for %s", job_id
            )
        try:
            self._terminate_process_group(process.pid, process=process, timeout=timeout)
        except Exception:
            logger.exception("Failed to terminate rolled-back Python job %s", job_id)
            try:
                with self._lock:
                    entry = self._store.get_job(job_id)
                    if entry:
                        self._store.update_job_backend_id(
                            job_id, str(process.pid), status="Running"
                        )
                        self._store.compare_and_set_job_status(
                            job_id, ("Pending", "Running"), "Canceling"
                        )
                        current = self._store.get_job(job_id) or entry
                        self._jobs.setdefault(
                            job_id,
                            Job(
                                id=job_id,
                                network_arch=current.get("network_arch", ""),
                                action=current.get("action", ""),
                                workspace_id=current.get("workspace_id", "local"),
                                backend_type="virtualenv",
                                status="Canceling",
                                backend_job_id=str(process.pid),
                                results_dir=current.get("results_dir", ""),
                                local_results_dir=current.get(
                                    "local_results_dir", ""
                                ),
                            ),
                        )
                    self._processes[job_id] = process
                    self._hooks.setdefault(job_id, {})
            except Exception:
                logger.exception(
                    "Failed to retain recoverable Python job identity for %s",
                    job_id,
                )
            return False
        try:
            with self._lock:
                self._processes.pop(job_id, None)
                self._jobs.pop(job_id, None)
                self._hooks.pop(job_id, None)
                entry = self._store.get_job(job_id)
                if entry:
                    self._store.compare_and_set_job_status(
                        job_id, ("Pending", "Running"), "Error"
                    )
        except Exception:
            logger.exception("Failed to persist rollback for Python job %s", job_id)
        return True

    @staticmethod
    def _terminate_process_group(
        pid: int,
        *,
        process: subprocess.Popen | None = None,
        timeout: float = 5.0,
    ) -> None:
        def group_exists() -> bool:
            try:
                os.killpg(pid, 0)
                return True
            except ProcessLookupError:
                return False
            except PermissionError:
                return True

        try:
            os.killpg(pid, signal.SIGTERM)
        except ProcessLookupError:
            return

        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if process is not None:
                process.poll()
            if not group_exists():
                return
            time.sleep(0.05)

        try:
            os.killpg(pid, signal.SIGKILL)
        except ProcessLookupError:
            return
        if process is not None:
            process.wait()
        kill_deadline = time.monotonic() + max(1.0, timeout)
        while time.monotonic() < kill_deadline:
            if not group_exists():
                return
            time.sleep(0.05)
        raise RuntimeError(f"Process group {pid} survived SIGKILL")

    @staticmethod
    def _validate_gpu_request(
        gpu_count: int,
        gpu_ids: Sequence[int] | str | None,
    ) -> list[int] | None:
        if isinstance(gpu_count, bool) or not isinstance(gpu_count, int) or gpu_count < 0:
            raise ValueError("gpu_count must be a non-negative integer")
        if gpu_ids is None:
            return None
        if isinstance(gpu_ids, str):
            raw_ids = [] if not gpu_ids.strip() else gpu_ids.split(",")
        elif isinstance(gpu_ids, Sequence):
            raw_ids = list(gpu_ids)
        else:
            raise TypeError("gpu_ids must be a sequence of integers or a comma-separated string")
        normalized = []
        for device_id in raw_ids:
            if isinstance(device_id, bool):
                raise ValueError("gpu_ids must contain non-negative integers")
            if isinstance(device_id, str):
                token = device_id.strip()
                if not re.fullmatch(r"[+-]?\d+", token):
                    raise ValueError("gpu_ids must contain non-negative integers")
                normalized.append(int(token))
                continue
            try:
                normalized.append(operator.index(device_id))
            except TypeError as exc:
                raise ValueError(
                    "gpu_ids must contain non-negative integers"
                ) from exc
        if any(device_id < 0 for device_id in normalized):
            raise ValueError("gpu_ids must contain non-negative integers")
        if len(set(normalized)) != len(normalized):
            raise ValueError("gpu_ids must not contain duplicates")
        if len(normalized) != gpu_count:
            raise ValueError("gpu_count must match the number of gpu_ids")
        return normalized

    @staticmethod
    def _validate_local_inputs(specs: dict, inputs: dict | None) -> None:
        if inputs is None:
            return
        if not isinstance(inputs, dict):
            raise TypeError("inputs must be a dictionary of declared spec keys")
        for spec_key, declaration in inputs.items():
            if not isinstance(spec_key, str):
                raise TypeError("Declared input spec keys must be strings")
            declared_value = _get_nested(specs, spec_key)
            remote = None if declared_value is _MISSING else _find_remote_uri(declared_value)
            # Also catches path-keyed mappings such as {local_path: s3_uri}.
            remote = remote or _find_remote_uri(declaration)
            if remote:
                raise ValueError(
                    "VirtualEnvSDK supports local declared inputs only; "
                    f"{spec_key!r} resolves to unsupported remote URI {remote!r}"
                )

    @staticmethod
    def _route_outputs(specs: dict, outputs: dict | list | None, results_dir: Path) -> dict[str, str]:
        if outputs is None:
            return {}
        if isinstance(outputs, dict):
            declarations = outputs
        elif isinstance(outputs, list):
            declarations = {key: {} for key in outputs}
        else:
            raise TypeError("outputs must be a dictionary or list of declared spec keys")

        routed: dict[str, str] = {}
        used_paths: set[Path] = set()
        for spec_key, metadata in declarations.items():
            tokens = _parse_spec_path(spec_key)
            safe_name = "_".join(
                re.sub(r"[^A-Za-z0-9_-]", "_", str(token)) for token in tokens
            )
            output_path = results_dir / safe_name
            if output_path in used_paths:
                raise ValueError(f"Declared output paths collide after normalization: {spec_key!r}")
            used_paths.add(output_path)

            output_type = metadata.get("type", "folder") if isinstance(metadata, dict) else "folder"
            if output_type in {"file", "model"}:
                output_path.parent.mkdir(parents=True, exist_ok=True)
            else:
                output_path.mkdir(parents=True, exist_ok=True)
            _set_nested(specs, spec_key, str(output_path))
            routed[spec_key] = str(output_path)
        return routed

    @staticmethod
    def _write_spec(config_path: Path, specs: dict, config_format: str) -> None:
        config_format = VirtualEnvSDK._validate_config_format(config_format)
        specs = normalize_specs(specs, allow_none=config_format != "toml")
        if config_format == "json":
            config_path.write_text(
                json.dumps(
                    specs, indent=2, sort_keys=True, allow_nan=False
                ) + "\n",
                encoding="utf-8",
            )
            return
        if config_format == "yaml":
            import yaml
            config_path.write_text(yaml.safe_dump(specs, sort_keys=False), encoding="utf-8")
            return
        if config_format == "toml":
            import tomli_w

            config_path.write_text(tomli_w.dumps(specs), encoding="utf-8")
            return

    @staticmethod
    def _validate_config_format(config_format: str) -> str:
        if not isinstance(config_format, str):
            raise TypeError("config_format must be one of: json, yaml, toml")
        normalized = config_format.lower()
        if normalized not in {"json", "yaml", "toml"}:
            raise ValueError("config_format must be one of: json, yaml, toml")
        if normalized == "toml":
            try:
                import tomli_w  # noqa: F401
            except ImportError as exc:
                raise RuntimeError(
                    "TOML spec serialization requires an optional writer. "
                    "Install 'nvidia-tao-sdk[toml]' or use config_format='json'/'yaml'."
                ) from exc
        return normalized

    @staticmethod
    def _render_arg(token: str, placeholders: dict[str, str]) -> str:
        unknown = {
            match.group(1) for match in _PLACEHOLDER_RE.finditer(token)
            if match.group(1) not in placeholders
        }
        if unknown:
            names = ", ".join(sorted(unknown))
            raise ValueError(f"Unsupported script_args placeholder(s): {names}")
        rendered = token
        for name, value in placeholders.items():
            rendered = rendered.replace("{" + name + "}", value)
        return rendered

