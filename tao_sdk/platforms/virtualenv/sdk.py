    def _watch_process(self, job_id: str, process: subprocess.Popen) -> None:
        return_code = process.wait()
        self._finalize_after_process_group_quiescence(
            job_id, process.pid, return_code, process=process
        )

    def _finalize_after_process_group_quiescence(
        self,
        job_id: str,
        pid: int,
        return_code: int,
        *,
        process: subprocess.Popen | None = None,
    ) -> str:
        """Finalize only after forked/background writers have also stopped."""
        with self._lock:
            entry = self._store.get_job(job_id)
            metadata = self._read_metadata_from_entry(entry) if entry else {}
            exit_record = self._read_exit_record(metadata)
            if not exit_record or exit_record.get("group_quiescent") is not True:
                logger.warning(
                    "Job %s parent exited but its durable process-group quiescence "
                    "record is missing or false",
                    job_id,
                )
                return entry.get("status", "Running") if entry else "Unknown"
            return self._finalize_job(job_id, return_code)

    @staticmethod
    def _read_record(path_value: str | None) -> dict | None:
        if not path_value:
            return None
        try:
            payload = json.loads(Path(path_value).read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return None
        return payload if isinstance(payload, dict) else None

    @classmethod
    def _read_exit_record(cls, metadata: dict) -> dict | None:
        return cls._read_record(metadata.get("exit_record_path"))

    @classmethod
    def _read_launcher_record(cls, metadata: dict) -> dict | None:
        return cls._read_record(metadata.get("launcher_record_path"))

    @staticmethod
    def _authorize_launch(metadata: dict) -> None:
        """Open the wrapper gate only after durable registration succeeds."""
        gate_path = metadata.get("start_gate_path")
        if gate_path:
            Path(gate_path).touch(exist_ok=True)

    @staticmethod
    def _request_cancel(metadata: dict) -> None:
        """Persist cancellation so a not-yet-started wrapper cannot train."""
        cancel_path = metadata.get("cancel_path")
        if cancel_path:
            Path(cancel_path).touch(exist_ok=True)

    def _transition_active_job(
        self,
        entry: dict,
        metadata: dict,
        status: str,
        message: str,
    ) -> tuple[str, str]:
        """Atomically transition a live job and return authoritative state."""
        transitioned = self._store.compare_and_set_job_status(
            entry["job_id"], ("Pending", "Running"), status
        )
        current_entry = self._store.get_job(entry["job_id"]) or entry
        current_status = current_entry.get("status", status)
        if transitioned:
            metadata.update({"status": current_status, "message": message})
            self._write_metadata(
                Path(current_entry["local_results_dir"]).parent, metadata
            )
            return current_status, message

        current_metadata = self._read_metadata_from_entry(current_entry)
        current_message = current_metadata.get("message", "")
        if current_metadata.get("status") != current_status:
            current_message = _TERMINAL_STATUS_MESSAGES.get(
                current_status, current_message
            )
        return current_status, current_message

    def _resolve_process_identity(
        self, entry: dict, metadata: dict, *, register: bool = True,
    ) -> tuple[int, dict]:
        """Merge the durable launcher identity into store metadata."""
        launcher_record = self._read_launcher_record(metadata) or {}
        pid_value = (
            entry.get("backend_job_id")
            or metadata.get("pid")
            or launcher_record.get("pid")
            or 0
        )
        try:
            pid = int(pid_value)
        except (TypeError, ValueError):
            pid = 0
        marker = (
            metadata.get("process_start_marker")
            or launcher_record.get("process_start_marker")
        )
        attach_allowed = True
        if register and pid and not entry.get("backend_job_id"):
            attach_allowed = self._store.update_job_backend_id(
                entry["job_id"], str(pid), "Running"
            )
        if (
            pid
            and (metadata.get("pid") != pid or not metadata.get("process_start_marker"))
        ):
            metadata.update({
                "pid": pid,
                "process_start_marker": marker,
                "status": "Running",
                "message": f"Process {pid} is running",
            })
        if pid and register and attach_allowed:
            self._write_metadata(Path(entry["local_results_dir"]).parent, metadata)
            self._authorize_launch(metadata)
        return pid, metadata

    @staticmethod
    def _process_matches(pid: int, metadata: dict) -> bool:
        """Verify that ``pid`` is this job's launcher before signaling it."""
        if pid <= 0:
            return False
        try:
            os.kill(pid, 0)
            if os.getpgid(pid) != pid:
                return False
        except (OSError, ValueError):
            return False

        expected_marker = metadata.get("process_start_marker")
        if expected_marker and _process_start_marker(pid) != str(expected_marker):
            return False

        launcher_path = metadata.get("launcher_path")
        if launcher_path:
            try:
                cmdline = Path(f"/proc/{pid}/cmdline").read_bytes().split(b"\0")
            except OSError:
                return False
            if os.fsencode(launcher_path) not in cmdline:
                return False
        return True

    def _finalize_job(self, job_id: str, return_code: int) -> str:
        hook_name = None
        hook = None
        job = None
        with self._lock:
            entry = self._store.get_job(job_id)
            if not entry:
                return "Unknown"
            previous = entry.get("status", "Running")
            metadata = self._read_metadata_from_entry(entry)
            exit_record = self._read_exit_record(metadata)
            recorded_code = (exit_record or {}).get("return_code")
            if isinstance(recorded_code, int) and not isinstance(recorded_code, bool):
                return_code = recorded_code
            cancel_path = metadata.get("cancel_path")
            cancel_requested = bool(
                cancel_path and Path(cancel_path).exists()
            )
            if (
                previous in {"Canceling", "Canceled"}
                or cancel_requested
                or job_id in self._canceled
            ):
                proposed_status = "Canceled"
                proposed_message = "Process group was canceled"
            elif return_code == 0:
                proposed_status = "Complete"
                proposed_message = "Process exited successfully"
            else:
                proposed_status = "Error"
                if return_code < 0:
                    proposed_message = f"Process terminated by signal {-return_code}"
                else:
                    proposed_message = f"Process exited with code {return_code}"

            transitioned = False
            if previous in _TERMINAL_STATUSES:
                status = previous
            else:
                transitioned = self._store.compare_and_set_job_status(
                    job_id, ("Pending", "Running", "Canceling"), proposed_status
                )
                current_entry = self._store.get_job(job_id) or entry
                status = current_entry.get("status", proposed_status)
                entry = current_entry

            if status == proposed_status:
                message = proposed_message
            else:
                message = self._read_metadata_from_entry(entry).get(
                    "message", f"Job already reached terminal status {status}"
                )
            if status == "Canceled":
                message = "Process group was canceled"
                existing_code = metadata.get("return_code")
                return_code = (
                    existing_code if existing_code is not None else -signal.SIGTERM
                )
            job = self._jobs.get(job_id) or self._load_job_from_entry(entry)
            job.status = status
            metadata.update({
                "status": status,
                "return_code": return_code,
                "message": message,
            })
            self._write_metadata(Path(entry["local_results_dir"]).parent, metadata)
            self._processes.pop(job_id, None)
            if transitioned and status == "Complete":
                hook_name = "on_complete"
            elif transitioned and status == "Error":
                hook_name = "on_error"
            if hook_name:
                hook = self._hooks.get(job_id, {}).get(hook_name)
            self._hooks.pop(job_id, None)

        if hook:
            try:
                hook(job)
            except Exception:
                logger.exception("Hook %s raised for Python job %s", hook_name, job_id)
        return status

    def get_job_status(self, job_id: str) -> JobStatus:
        with self._lock:
            entry = self._store.get_job(job_id)
            if not entry:
                return JobStatus(job_id=job_id, status="Unknown", message="Job not found")
            stored_status = entry.get("status", "Unknown")
            if stored_status in _TERMINAL_STATUSES:
                metadata = self._read_metadata_from_entry(entry)
                message = (
                    metadata.get("message")
                    or _TERMINAL_STATUS_MESSAGES[stored_status]
                )
                if metadata.get("status") != stored_status:
                    message = _TERMINAL_STATUS_MESSAGES[stored_status]
                    metadata.update({"status": stored_status, "message": message})
                    self._write_metadata(
                        Path(entry["local_results_dir"]).parent, metadata
                    )
                return JobStatus(
                    job_id=job_id, status=stored_status, message=message
                )
            process = self._processes.get(job_id)
            if process is not None:
                return_code = process.poll()
                if return_code is None:
                    status = "Running"
                    message = f"Process {process.pid} is running"
                else:
                    status = self._finalize_after_process_group_quiescence(
                        job_id,
                        process.pid,
                        return_code,
                        process=process,
                    )
                    entry = self._store.get_job(job_id) or entry
                    message = self._read_metadata_from_entry(entry).get("message", "")
            else:
                status = entry.get("status", "Unknown")
                metadata = self._read_metadata_from_entry(entry)
                message = metadata.get("message", "")
                if status in {"Pending", "Running"}:
                    pid, metadata = self._resolve_process_identity(entry, metadata)
                    current_entry = self._store.get_job(job_id) or entry
                    current_status = current_entry.get("status", status)
                    if current_status in _TERMINAL_STATUSES:
                        return JobStatus(
                            job_id=job_id,
                            status=current_status,
                            message=self._read_metadata_from_entry(current_entry).get(
                                "message", ""
                            ),
                        )
                    exit_record = self._read_exit_record(metadata)
                    recorded_code = (exit_record or {}).get("return_code")
                    if isinstance(recorded_code, int) and not isinstance(
                        recorded_code, bool
                    ):
                        status = self._finalize_after_process_group_quiescence(
                            job_id, pid, recorded_code
                        )
                        entry = self._store.get_job(job_id) or entry
                        message = self._read_metadata_from_entry(entry).get(
                            "message", ""
                        )
                    elif self._process_matches(pid, metadata):
                        status = "Running"
                        message = f"Process {pid} is running"
                    elif status == "Pending" and pid == 0:
                        try:
                            launch_age = time.time() - float(
                                metadata.get("launch_started_at")
                            )
                        except (TypeError, ValueError):
                            launch_age = _PENDING_LAUNCH_GRACE_SECONDS
                        if launch_age < _PENDING_LAUNCH_GRACE_SECONDS:
                            message = "Waiting for the durable launcher record"
                        else:
                            message = (
                                "Python launcher identity is unavailable; keeping "
                                "the job non-terminal for safe manual recovery"
                            )
                    else:
                        message = (
                            "Python launcher ended without a durable quiescence "
                            "record; keeping the job non-terminal"
                        )
            return JobStatus(job_id=job_id, status=status, message=message)

    def get_job_logs(self, job_id: str, tail: int | None = None) -> str:
        with self._lock:
            entry = self._store.get_job(job_id)
        if not entry:
            return ""
        log_path = Path(entry["local_results_dir"]).parent / "logs" / "job.log"
        if not log_path.is_file():
            return ""
        if tail is None:
            return log_path.read_text(encoding="utf-8", errors="replace")
        return _read_tail(log_path, tail)

    def iter_job_log_chunks(
        self, job_id: str, chunk_size: int = 256 * 1024,
    ) -> Iterator[str]:
        """Stream a job log in bounded chunks for terminal metric scans."""
        if isinstance(chunk_size, bool) or not isinstance(chunk_size, int):
            raise TypeError("chunk_size must be a positive integer")
        if chunk_size <= 0:
            raise ValueError("chunk_size must be a positive integer")
        with self._lock:
            entry = self._store.get_job(job_id)
        if not entry:
            return
        log_path = Path(entry["local_results_dir"]).parent / "logs" / "job.log"
        if not log_path.is_file():
            return
        with log_path.open(encoding="utf-8", errors="replace") as stream:
            while True:
                chunk = stream.read(chunk_size)
                if not chunk:
                    return
                yield chunk

    def cancel_job(self, job_id: str, timeout: float = 5.0) -> bool:
        with self._lock:
            entry = self._store.get_job(job_id)
            if not entry or entry.get("status") in _TERMINAL_STATUSES:
                return False
            process = self._processes.get(job_id)
            metadata = self._read_metadata_from_entry(entry)
            pid, metadata = self._resolve_process_identity(
                entry, metadata, register=False
            )
            if process is not None:
                return_code = process.poll()
                if return_code is not None:
                    terminal_status = self._finalize_after_process_group_quiescence(
                        job_id,
                        process.pid,
                        return_code,
                        process=process,
                    )
                    if terminal_status in _TERMINAL_STATUSES:
                        return False
                    # The wrapper can exit before a forked training child. A
                    # false/missing group-quiescence record means cancellation
                    # must still terminate this exact in-memory process group.
            else:
                exit_record = self._read_exit_record(metadata)
                recorded_code = (exit_record or {}).get("return_code")
                if isinstance(recorded_code, int) and not isinstance(
                    recorded_code, bool
                ):
                    terminal_status = self._finalize_after_process_group_quiescence(
                        job_id, pid, recorded_code
                    )
                    if terminal_status in _TERMINAL_STATUSES:
                        return False
                if pid and not self._process_matches(pid, metadata):
                    # Never signal a persisted PGID after its launcher identity
                    # is gone; the number may have been reused by another job.
                    return False
            if entry.get("status") != "Canceling":
                if not self._store.compare_and_set_job_status(
                    job_id, ("Pending", "Running"), "Canceling"
                ):
                    return False
            self._request_cancel(metadata)
            self._canceled.add(job_id)
            job = self._jobs.get(job_id)
            if job:
                job.status = "Canceling"

        try:
            if pid:
                self._terminate_process_group(pid, process=process, timeout=timeout)
        except Exception as exc:
            logger.warning(
                "Could not confirm process-group termination for job %s: %s",
                job_id,
                exc,
            )
            return False

        with self._lock:
            current_entry = self._store.get_job(job_id) or entry
            current_status = current_entry.get("status", "Unknown")
            if current_status == "Canceling":
                self._store.compare_and_set_job_status(
                    job_id, ("Canceling",), "Canceled"
                )
                current_entry = self._store.get_job(job_id) or current_entry
                current_status = current_entry.get("status", "Unknown")
            if current_status != "Canceled":
                return False
            job = self._jobs.get(job_id)
            if job:
                job.status = "Canceled"

        metadata.update({
            "status": "Canceled",
            "return_code": (
                process.returncode
                if process is not None
                else (-signal.SIGTERM if pid else None)
            ),
            "message": (
                "Process group was canceled"
                if pid else "Job was canceled before launch"
            ),
        })
        self._write_metadata(Path(entry["local_results_dir"]).parent, metadata)
        return True

    def get_failure_analysis(self, job_id: str) -> dict | None:
        status = self.get_job_status(job_id)
        if status.status != "Error":
            return None
        with self._lock:
            entry = self._store.get_job(job_id)
        if not entry:
            return None
        metadata = self._read_metadata_from_entry(entry)
        return_code = metadata.get("return_code")
        logs = self.get_job_logs(job_id, tail=80)
        lowered = logs.lower()
        if "cuda out of memory" in lowered or "memoryerror" in lowered:
            category = "out_of_memory"
        elif isinstance(return_code, int) and return_code < 0:
            category = "signal"
        elif return_code is None:
            category = "lost_process"
        else:
            category = "nonzero_exit"
        return {
            "job_id": job_id,
            "status": "Error",
            "category": category,
            "reason": metadata.get("message") or status.message,
            "return_code": return_code,
            "log_tail": logs,
        }

    # ------------------------------------------------------------------
    # Persistent metadata and result access
    # ------------------------------------------------------------------

    def get_job(self, job_id: str) -> dict | None:
        self.get_job_status(job_id)
        with self._lock:
            return self._store.get_job(job_id)

    def list_jobs(self, status: str | None = None) -> list[dict]:
        with self._lock:
            active_job_ids = list(self._processes)
        for job_id in active_job_ids:
            self.get_job_status(job_id)
        with self._lock:
            return self._store.list_jobs(status=status)

    def get_job_results_dir(self, job_id: str) -> str:
        with self._lock:
            entry = self._store.get_job(job_id)
        return entry.get("local_results_dir", "") if entry else ""

    def delete_job_artifacts(self, job_id: str) -> bool:
        """Delete only the result subtree for one local Python job."""
        with self._lock:
            entry = self._store.get_job(job_id)
        if not entry:
            return False
        results_dir = entry.get("local_results_dir", "")
        expected = self.jobs_dir.resolve() / job_id / "results"
        try:
            require_terminal_job(entry)
            resolved_job_dir = expected.parent.resolve()
            if resolved_job_dir.parent != self.jobs_dir.resolve():
                raise ValueError("job directory escapes the virtualenv jobs root")
            deleted = delete_local_job_results(
                results_dir, job_id, expected_path=expected
            )
            if deleted:
                self._store.delete_checkpoints(job_id)
            return deleted
        except (OSError, ValueError) as exc:
            logger.warning("Could not delete artifacts for job %s: %s", job_id, exc)
            return False

    def list_results(self, job_id: str) -> list[str]:
        results_dir = self.get_job_results_dir(job_id)
        if not results_dir:
            return []
        root = Path(results_dir)
        if not root.is_dir():
            return []
        return sorted(
            path.relative_to(root).as_posix()
            for path in root.rglob("*")
            if path.is_file()
        )

    def get_results(self, job_id: str) -> list[str]:
        """Alias for :meth:`list_results` for capability-oriented callers."""
        return self.list_results(job_id)

    def read_job_result_file(self, job_id: str, relative_path: str) -> str:
        results_dir = self.get_job_results_dir(job_id)
        if not results_dir:
            return ""
        root = Path(results_dir).resolve()
        candidate = (root / relative_path).resolve()
        try:
            candidate.relative_to(root)
        except ValueError as exc:
            raise ValueError("Result path must stay within the job results directory") from exc
        if not candidate.is_file():
            return ""
        return candidate.read_text(encoding="utf-8", errors="replace")

    def get_checkpoints(self, job_id: str) -> list[str]:
        return [
            path for path in self.list_results(job_id)
            if path.lower().endswith(_CHECKPOINT_EXTENSIONS)
        ]

    def _load_job_from_entry(self, entry: dict) -> Job:
        job = Job(
            id=entry["job_id"],
            network_arch=entry.get("network_arch", ""),
            action=entry.get("action", ""),
            workspace_id=entry.get("workspace_id", "local"),
            backend_type="virtualenv",
            status=entry.get("status", "Unknown"),
            created_at=entry.get("created_at", ""),
            backend_job_id=entry.get("backend_job_id", ""),
            parent_job_id=entry.get("parent_job_id", "") or "",
            results_dir=entry.get("results_dir", ""),
            local_results_dir=entry.get("local_results_dir", ""),
        )
        self._jobs[job.id] = job
        return job

    @staticmethod
    def _write_metadata(job_dir: Path, metadata: dict) -> None:
        metadata_path = job_dir / "metadata.json"
        temp_path = job_dir / f".metadata.{uuid.uuid4().hex}.tmp"
        try:
            temp_path.write_text(
                json.dumps(metadata, indent=2, sort_keys=True) + "\n",
                encoding="utf-8",
            )
            temp_path.replace(metadata_path)
        finally:
            # replace() removes the source; unlink only handles failed writes.
            temp_path.unlink(missing_ok=True)

    @staticmethod
    def _read_metadata_from_entry(entry: dict) -> dict:
        results_dir = entry.get("local_results_dir") or entry.get("results_dir")
        if not results_dir:
            return {}
        metadata_path = Path(results_dir).parent / "metadata.json"
        try:
            return json.loads(metadata_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return {}
